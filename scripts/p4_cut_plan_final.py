# ---------- C. 合并关键词并重算 ----------
SUBKEY = {}
import importlib.util
# 直接读 raw 已含子链分桶，仅对 unmapped 用 KEYADD 再分
for wname, subs in raw.items():
    if wname.startswith('__'): continue
    SUBKEY[wname] = {s: [] for s in subs if not s.startswith('__')}
    for s, kws in KEYADD.get(wname, {}).items():
        SUBKEY[wname].setdefault(s, []).extend(kws)

# 单链族：银行/军工 保留原链名不切割（主营同质；银行=存贷款，军工=装备制造统一链）
SINGLE_CHAIN = {'银行产业链', '军工产业链'}

def sub_attr2(wname, yw, products):
    text = (yw or '') + ' ' + ' '.join(products or [])
    best, best_n = None, 0
    for sub, kws in SUBKEY.get(wname, {}).items():
        n = sum(1 for k in kws if k in text)
        if n > best_n:
            best, best_n = sub, n
    return best, best_n

final = {}          # 子链 -> {parent, stocks:[]}
cross_removed = {}  # 宽链 -> [(code,name,原因)]
independent = []    # 独立股池

def add_stock(sub_chain, code, info):
    final.setdefault(sub_chain, {'parent': None, 'stocks': []})
    final[sub_chain]['stocks'].append({
        'code': code, 'name': info.get('name',''), 'yw': info.get('yw',''),
        'report_date': info.get('report_date',''), 'products': info.get('products',[]),
        'llm_seed': info.get('llm_seed'), 'rule': info.get('rule'),
    })

