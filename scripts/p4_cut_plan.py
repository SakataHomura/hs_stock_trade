def sub_attr(wname, yw, products):
    """返回 (子链, 命中数) 或 (None, 0)"""
    text = (yw or '') + ' ' + ' '.join(products or [])
    subs = SUBKEY.get(wname, {})
    best, best_n = None, 0
    for sub, kws in subs.items():
        n = sum(1 for k in kws if k in text)
        if n > best_n:
            best, best_n = sub, n
    return best, best_n

plan = {}
stats = {}
for wname, stocks in chain_stocks.items():
    sub_map = defaultdict(list)  # 子链 -> [codes]
    unmapped = []
    for code, info in stocks.items():
        prods = [p.split(':')[0] for p in info['products']]
        sub, n = sub_attr(wname, info['yw'], prods)
        if sub and n >= 1:
            sub_map[sub].append(code)
        else:
            unmapped.append(code)
    plan[wname] = {s: sorted(c) for s, c in sub_map.items()}
    plan[wname]['__unmapped__'] = sorted(unmapped)
    stats[wname] = {s: len(c) for s, c in sub_map.items()}
    stats[wname]['__unmapped__'] = len(unmapped)

for wname, st in stats.items():
    print(f'{wname}: ' + ' | '.join(f'{k}={v}' for k, v in st.items() if v))

